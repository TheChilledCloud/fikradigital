  var LS_KEY = 'mawj-lang';

  function applyLang(lang) {
    var d = dicts[lang] || dicts.en;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title = lang === 'de' ? 'MAWJ — Ein Haus am Rand des Meeres · Latakia'
      : lang === 'ar' ? 'موج — بيت على حافة البحر · اللاذقية'
      : 'MAWJ — A House on the Edge of the Sea · Latakia';

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (d[k] !== undefined) el.textContent = d[k];
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-html');
      if (d[k] !== undefined) el.innerHTML = d[k];
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-alt');
      if (d[k] !== undefined) el.setAttribute('alt', d[k]);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      var k = el.getAttribute('data-i18n-placeholder');
      if (d[k] !== undefined) el.setAttribute('placeholder', d[k]);
    });
    document.querySelectorAll('.lang-switch [data-lang]').forEach(function (b) {
      b.classList.toggle('active', b.dataset.lang === lang);
    });

    window.__mawjLang = lang;
    document.dispatchEvent(new CustomEvent('mawj:langchange', { detail: lang }));
  }

  var saved = null;
  try { saved = localStorage.getItem(LS_KEY); } catch (e) {}
  applyLang(['en', 'de', 'ar'].indexOf(saved) !== -1 ? saved : 'en');

  document.querySelectorAll('[data-lang]').forEach(function (b) {
    b.addEventListener('click', function () {
      try { localStorage.setItem(LS_KEY, b.dataset.lang); } catch (e) {}
      applyLang(b.dataset.lang);
    });
  });

  window.MAWJ_I18N = dicts;
